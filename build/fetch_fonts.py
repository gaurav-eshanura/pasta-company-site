"""Download the woff2 files the site needs and emit a local @font-face sheet.

Self-hosting keeps the site independent of a third-party CDN and avoids a
render-blocking round trip on first paint.

Every outbound request is pinned to a host allowlist and every write path is
resolved and checked for containment, so neither the remote response nor a
malformed stylesheet can steer the fetch off Google or the write out of
assets/fonts.
"""

from __future__ import annotations

import re
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
CSS_OUT = ROOT / "assets" / "css" / "fonts.css"

# Only these hosts are ever contacted, and only over TLS.
ALLOWED_HOSTS = {"fonts.googleapis.com", "fonts.gstatic.com"}
ALLOWED_SCHEMES = {"https"}

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
)

FAMILIES = [
    # Display serif for the wordmark and headings.
    ("Playfair+Display:wght@500;600;700;800", "Playfair Display", (500, 600, 700, 800)),
    # Brush script for the Hinglish headline and the pack-note badge.
    ("Kaushan+Script", "Kaushan Script", (400,)),
    # UI and body face.
    ("Poppins:wght@400;500;600;700", "Poppins", (400, 500, 600, 700)),
]


def check_url(url: str) -> str:
    """Reject anything that is not plain HTTPS to an allowlisted host."""
    parts = urllib.parse.urlsplit(url)
    if parts.scheme not in ALLOWED_SCHEMES:
        raise ValueError(f"refusing non-HTTPS url: {url}")
    if parts.hostname not in ALLOWED_HOSTS:
        raise ValueError(f"refusing off-allowlist host: {parts.hostname}")
    return url


def safe_join(base: Path, name: str) -> Path:
    """Join a remote-supplied filename into `base`, refusing to escape it."""
    if not re.fullmatch(r"[A-Za-z0-9._-]+\.woff2", name):
        raise ValueError(f"refusing suspicious font filename: {name!r}")
    root = base.resolve()
    dest = (root / name).resolve()
    if root not in dest.parents:
        raise ValueError(f"refusing path escape: {dest}")
    return dest


class PinnedRedirectHandler(urllib.request.HTTPRedirectHandler):
    """Re-check the allowlist after every redirect hop."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        check_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def fetch(url: str) -> bytes:
    req = urllib.request.Request(check_url(url), headers={"User-Agent": UA})
    opener = urllib.request.build_opener(PinnedRedirectHandler)
    with opener.open(req, timeout=30) as r:
        check_url(r.geturl())  # confirm the post-redirect target too
        return r.read()


def main() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)

    blocks: list[str] = ["/* Generated by build/fetch_fonts.py -- do not edit by hand. */\n"]

    for query, family, weights in FAMILIES:
        css = fetch(f"https://fonts.googleapis.com/css2?family={query}&display=swap").decode("utf-8")
        # Google's CSS emits one @font-face per unicode-range slice; we only
        # want latin + latin-ext so we do not ship Devanagari or Cyrillic files.
        faces = re.findall(r"/\*\s*([a-z-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
        for subset, face in faces:
            if subset not in ("latin", "latin-ext"):
                continue
            weight = re.search(r"font-weight:\s*(\d+)", face).group(1)
            if int(weight) not in weights:
                continue
            url = re.search(r"url\((https://[^)]+\.woff2)\)", face).group(1)
            style = re.search(r"font-style:\s*(\w+)", face).group(1)
            unicode_range = re.search(r"unicode-range:\s*([^;]+);", face).group(1).strip()

            name = f"{query.split(':')[0].split('+')[0].lower()}-{weight}-{subset}.woff2"
            dest = safe_join(FONT_DIR, name)
            if not dest.exists():
                dest.write_bytes(fetch(url))
                print(f"  downloaded {name} ({dest.stat().st_size // 1024} KB)")

            blocks.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                f"  font-style: {style};\n"
                f"  font-weight: {weight};\n"
                f"  font-display: swap;\n"
                f"  src: url('../fonts/{name}') format('woff2');\n"
                f"  unicode-range: {unicode_range};\n"
                "}\n"
            )

    CSS_OUT.write_text("\n".join(blocks), encoding="utf-8")
    print(f"wrote {len(blocks) - 1} @font-face rules -> assets/css/fonts.css")


if __name__ == "__main__":
    main()
